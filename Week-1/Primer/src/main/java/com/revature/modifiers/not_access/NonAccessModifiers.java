package com.revature.modifiers.not_access;

public class NonAccessModifiers {
    /*
        There are some keywords you need to be aware of that do not control access to resources
        - static: this makes a field/method class scoped
        - abstract: this makes classes unable to have an object made of them directly, methods have their implementation
                    defined in another location
        - final: final classes can not be extended, final fields can not have their reference changed, final methods
                 can not be overridden
     */
}
