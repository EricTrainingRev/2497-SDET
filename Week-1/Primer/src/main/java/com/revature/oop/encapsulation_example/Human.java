package com.revature.oop.encapsulation_example;

public class Human {

    private String name;
    private int age;

    public Human(String name, int age) {
        this.name = name;
        this.age = age;
    }

    /*
        This here is what is typically meant by "encapsulation" in Java: public methods are used to interact with
        private data in your classes
     */

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
